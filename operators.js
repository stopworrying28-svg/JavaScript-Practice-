console.log("Operators in JavaScript");
let a = 15;
let b = 5;

console.log("Arithmetic Operators");
console.log("Num1 + Num2 =", a + b);
console.log("Num1 - Num2 =", a - b);
console.log("Num1 * Num2 =", a * b);
console.log("Num1 / Num2 =", a / b);
console.log("Num1 % Num2 =", a % b);
console.log("++Num1 =", ++a);
console.log("Num2++ =", b++);
console.log("--Num1 =", --a);
console.log("Num2-- =", b--);
console.log("Num1 ** Num2 =", a ** b);
console.log("\n");

console.log("Comparison Operators")
console.log("Num1 == Num2 =", a == b);
console.log("Num1 === Num2 =", a === b);
console.log("Num1 >= Num2 =", a >= b);
console.log("Num1 <= Num2 =", a <= b);
console.log("Num1 != Num2 =", a != b);
console.log("Num1 !== Num2 =", a !== b);
console.log("\n");

console.log("Logical Operators");
console.log("Num1 == Num2 && Num1 >= Num2 =", a == b && a >= b );
console.log("Num1 == Num2 || Num1 >= Num2 =", a == b || a >= b );
console.log("!Num1 != Num2 =", !(a != b));